/// A concrete provider SDK adapter (OpenAI, Anthropic, Ollama, OpenRouter, ...) that
/// speaks the provider-neutral `LLMMessage`/`LLMStreamChunk` contract.
public protocol LLMClientProtocol: Sendable {
    /// The structured-output preparation behavior supported by this client.
    var structuredOutputAdapter: any StructuredOutputAdapter { get async }

    /// Streams a chat completion for the given messages/tools/parameters.
    func chatStream(
        messages: [LLMMessage],
        tools: [LLMToolDefinition]?,
        toolChoice: LLMToolChoice?,
        responseFormat: LLMResponseFormat?,
        generationParameters: GenerationParameters?
    ) async -> AsyncThrowingStream<LLMStreamChunk, Error>

    /// Streams a chat completion with explicit output modalities.
    func chatStream(
        messages: [LLMMessage],
        tools: [LLMToolDefinition]?,
        toolChoice: LLMToolChoice?,
        responseFormat: LLMResponseFormat?,
        generationParameters: GenerationParameters?,
        responseModalities: Set<ResponseModality>,
        audioOutput: AudioOutputOptions?
    ) async -> AsyncThrowingStream<LLMStreamChunk, Error>

    /// Sends a single non-streamed message and returns the full text response.
    func sendMessage(
        _ content: String,
        responseFormat: LLMResponseFormat?,
        generationParameters: GenerationParameters?
    ) async throws -> String

    /// Fetches the list of model names available from this provider/endpoint, if the
    /// provider supports discovery. Returns `nil` when unsupported (see default below).
    func fetchAvailableModels() async throws -> [String]?
}

public extension LLMClientProtocol {
    var structuredOutputAdapter: any StructuredOutputAdapter {
        DefaultStructuredOutputAdapter()
    }

    func chatStream(
        messages: [LLMMessage],
        tools: [LLMToolDefinition]?,
        toolChoice: LLMToolChoice?,
        responseFormat: LLMResponseFormat?,
        generationParameters: GenerationParameters?,
        responseModalities: Set<ResponseModality>,
        audioOutput: AudioOutputOptions?
    ) async -> AsyncThrowingStream<LLMStreamChunk, Error> {
        guard !responseModalities.contains(.audio), audioOutput == nil else {
            return AsyncThrowingStream { continuation in
                continuation.finish(throwing: MultimodalContentError.missingCapability(.audioOutput))
            }
        }
        return await chatStream(
            messages: messages,
            tools: tools,
            toolChoice: toolChoice,
            responseFormat: responseFormat,
            generationParameters: generationParameters
        )
    }

    func fetchAvailableModels() async throws -> [String]? {
        nil
    }

    /// Sends a single user message and returns the full accumulated text response.
    ///
    /// Providers that need custom retry wrapping (OpenAI, OpenRouter, Anthropic, Ollama)
    /// override this with their own `sendMessage`; providers without retry needs
    /// (FoundationModelsClient) rely on this default.
    func sendMessage(
        _ content: String,
        responseFormat: LLMResponseFormat? = nil,
        generationParameters: GenerationParameters? = nil
    ) async throws -> String {
        let stream = await chatStream(
            messages: [LLMMessage(role: .user, content: content)],
            tools: nil,
            toolChoice: nil,
            responseFormat: responseFormat,
            generationParameters: generationParameters
        )
        return try await accumulateStreamContent(from: stream)
    }
}

/// Accumulates text content from a stream of `LLMStreamChunk`s into a single string.
///
/// Extracted from the duplicated `fullContent += delta` loop that appeared in every
/// provider's `sendMessage` and in `LLMStreamClient.sendStructuredMessage`.
public func accumulateStreamContent(
    from stream: AsyncThrowingStream<LLMStreamChunk, Error>
) async throws -> String {
    var fullContent = ""
    for try await chunk in stream {
        if let delta = chunk.choices.first?.delta.content {
            fullContent += delta
        }
    }
    return fullContent
}

public func makeEmptyObjectSchema() -> Schema {
    if let schema = try? Schema(instance: #"{"type":"object","properties":{}}"#) {
        return schema
    }
    return ToolParameterSchema.object {}.schemaDefinition
}

private func encodeSchema(_ schema: Schema?) -> String? {
    guard let schema, let data = try? JSONEncoder().encode(schema) else { return nil }
    return String(decoding: data, as: UTF8.self)
}
