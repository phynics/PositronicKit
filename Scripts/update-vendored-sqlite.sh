#!/usr/bin/env bash
#
# Regenerate the vendored SQLite amalgamation under Sources/CPKSQLite.
#
# The amalgamation is downloaded from sqlite.org, verified against the pinned
# SHA3-256, and written together with a generated symbol-prefix header. The
# prefix header renames every public `sqlite3_*` symbol to `pk_sqlite3_*` so the
# copy cannot collide with the system libsqlite3 that Apple frameworks and other
# libraries load at runtime.
#
# Usage:
#   Scripts/update-vendored-sqlite.sh [--source DIR] [--dest DIR] [VERSION] [CODE]
#
# --source DIR regenerates from a local amalgamation directory (used by the
# fixture test and offline regeneration); it skips the download and hash check.
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)"
cd "$repo_root"

source_dir=""
dest="Sources/CPKSQLite"
positional=()
while [ "$#" -gt 0 ]; do
    case "$1" in
        --source) source_dir="${2:?--source requires a directory}"; shift 2 ;;
        --dest) dest="${2:?--dest requires a directory}"; shift 2 ;;
        -h|--help) sed -n '2,17p' "$0"; exit 0 ;;
        --*) echo "update-vendored-sqlite: unknown option: $1" >&2; exit 2 ;;
        *) positional+=("$1"); shift ;;
    esac
done

VERSION="${positional[0]:-3.54.0}"
# The numeric amalgamation code from the SQLite download page (3.54.0 ->
# 3540000: major, zero-padded minor, zero-padded patch, then "00").
AMALGAMATION_CODE="${positional[1]:-3540000}"
YEAR="2026"
# SHA3-256 of sqlite-amalgamation-<code>.zip as published on the SQLite
# download page. Update the pin together with VERSION and AMALGAMATION_CODE.
SHA3="7b670a62fdfbd672b75fef004cb703c8a3e87d3a5cc7d675b4a08337004a2d93"
BASE_URL="https://www.sqlite.org/${YEAR}/sqlite-amalgamation-${AMALGAMATION_CODE}.zip"

work=""
if [ -z "$source_dir" ]; then
    work="$(mktemp -d)"
    trap 'rm -rf "$work"' EXIT

    echo "Downloading $BASE_URL"
    curl --fail --location --silent --show-error "$BASE_URL" -o "$work/amalgamation.zip"

    actual="$(python3 - "$work/amalgamation.zip" <<'PY'
import hashlib, sys
print(hashlib.sha3_256(open(sys.argv[1], "rb").read()).hexdigest())
PY
)"
    if [ "$actual" != "$SHA3" ]; then
        echo "update-vendored-sqlite: SHA3-256 mismatch" >&2
        echo "  expected: $SHA3" >&2
        echo "  actual:   $actual" >&2
        exit 1
    fi

    python3 - "$work/amalgamation.zip" "$work" <<'PY'
import sys, zipfile
with zipfile.ZipFile(sys.argv[1]) as archive:
    archive.extractall(sys.argv[2])
PY
    source_dir="$work/sqlite-amalgamation-$AMALGAMATION_CODE"
fi

mkdir -p "$dest"

# Regenerate the prefix header from the amalgamation's sqlite3.h. Every distinct
# `sqlite3_*` identifier becomes a macro that renames it. Block and line comments
# are stripped first so prose cannot introduce a spurious rename.
python3 - "$source_dir" "$dest" "$VERSION" <<'PY'
import os, re, sys

source_dir, dest, version = sys.argv[1], sys.argv[2], sys.argv[3]
header = open(os.path.join(source_dir, "sqlite3.h"), encoding="utf-8").read()

stripped = re.sub(r"/\*.*?\*/", " ", header, flags=re.S)
stripped = re.sub(r"//[^\n]*", " ", stripped)
symbols = sorted(set(re.findall(r"\bsqlite3_[A-Za-z0-9_]+", stripped)))

lines = [
    "/*",
    "** Generated by Scripts/update-vendored-sqlite.sh. Do not edit by hand.",
    "**",
    f"** SQLite {version}. Renames every public `sqlite3_*` symbol to",
    "** `pk_sqlite3_*` so the vendored copy cannot collide with the system",
    "** libsqlite3 that other libraries load at runtime.",
    "*/",
    "#ifndef PK_SQLITE_PREFIX_H",
    "#define PK_SQLITE_PREFIX_H",
    "",
]
for symbol in symbols:
    lines.append(f"#define {symbol} pk_{symbol}")
lines.append("")
lines.append("#endif /* PK_SQLITE_PREFIX_H */")
lines.append("")

open(os.path.join(dest, "pk_sqlite_prefix.h"), "w", encoding="utf-8").write("\n".join(lines))

# The amalgamation embeds its own copy of sqlite3.h, so including the prefix
# header before anything else renames the declarations and the definitions in
# the same translation unit.
amalgamation = open(os.path.join(source_dir, "sqlite3.c"), encoding="utf-8").read()
marker = "#ifndef SQLITE_AMALGAMATION\n#define SQLITE_CORE 1\n"
if marker not in amalgamation:
    raise SystemExit("update-vendored-sqlite: unexpected sqlite3.c layout")
amalgamation = amalgamation.replace(
    marker,
    '#include "pk_sqlite_prefix.h"\n' + marker,
    1,
)
open(os.path.join(dest, "sqlite3.c"), "w", encoding="utf-8").write(amalgamation)

with open(os.path.join(dest, "sqlite3.h"), "w", encoding="utf-8") as out:
    out.write(header)
PY

cat > "$dest/VENDORED.md" <<EOF
# Vendored SQLite

This directory contains the SQLite ${VERSION} amalgamation (\`sqlite3.c\`, \`sqlite3.h\`)
from <https://www.sqlite.org/${YEAR}/sqlite-amalgamation-${AMALGAMATION_CODE}.zip>.

- SHA3-256: \`${SHA3}\`
- SQLite is in the public domain. See the SQLite blessing in \`sqlite3.c\` and the
  repository \`LICENSE\`/\`NOTICE\` for provenance.
- \`pk_sqlite_prefix.h\` is generated by \`Scripts/update-vendored-sqlite.sh\` and
  renames every public \`sqlite3_*\` symbol to \`pk_sqlite3_*\` for symbol isolation.

Run \`Scripts/update-vendored-sqlite.sh\` to regenerate this directory.
EOF

echo "Wrote $dest (SQLite $VERSION, $(wc -l < "$dest/sqlite3.c") lines of sqlite3.c)"
