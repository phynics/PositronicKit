#!/usr/bin/env bash
# update-flake-swift.sh — refresh the pinned swift.org toolchain in flake.nix.
#
# Usage: Scripts/update-flake-swift.sh <version>
#
# <version> is the full swift.org release version (for example 6.4.0). The
# script rewrites the version binding, the per-system download URLs, and the
# SHA-256 hashes inside the generated `swift-distributions` block of flake.nix.
# It uses `nix store prefetch-file`, so the recorded hash is exactly the
# fixed-output hash Nix verifies at build time.
#
# Set FLAKE_FILE to rewrite a different flake (used by the fixture test) and NIX
# to select a different Nix binary.
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
flake_file="${FLAKE_FILE:-$repo_root/flake.nix}"
nix_bin="${NIX:-nix}"

usage() {
  printf 'Usage: %s <version>\n' "${0##*/}" >&2
  printf 'Example: %s 6.4.0\n' "${0##*/}" >&2
}

if [ "$#" -ne 1 ]; then
  usage
  exit 2
fi

version="$1"
if ! printf '%s' "$version" | grep -Eq '^[0-9]+\.[0-9]+\.[0-9]+$'; then
  printf 'update-flake-swift: version must be MAJOR.MINOR.PATCH (got %s)\n' "$version" >&2
  exit 2
fi

if [ ! -f "$flake_file" ]; then
  printf 'update-flake-swift: flake not found: %s\n' "$flake_file" >&2
  exit 1
fi

if ! command -v "$nix_bin" >/dev/null 2>&1; then
  printf 'update-flake-swift: %s is required to compute the fixed-output hashes\n' "$nix_bin" >&2
  exit 1
fi

if ! command -v python3 >/dev/null 2>&1; then
  printf 'update-flake-swift: python3 is required to rewrite the flake\n' >&2
  exit 1
fi

x86_url="https://download.swift.org/swift-${version}-release/ubuntu2404/swift-${version}-RELEASE/swift-${version}-RELEASE-ubuntu24.04.tar.gz"
aarch64_url="https://download.swift.org/swift-${version}-release/ubuntu2404-aarch64/swift-${version}-RELEASE/swift-${version}-RELEASE-ubuntu24.04-aarch64.tar.gz"

prefetch_hash() {
  local url="$1"
  "$nix_bin" store prefetch-file --json --hash-type sha256 "$url" \
    | python3 -c 'import json, sys; print(json.load(sys.stdin)["hash"])'
}

x86_hash="$(prefetch_hash "$x86_url")"
aarch64_hash="$(prefetch_hash "$aarch64_url")"

FLAKE_FILE="$flake_file" \
UPDATE_VERSION="$version" \
UPDATE_X86_URL="$x86_url" UPDATE_X86_HASH="$x86_hash" \
UPDATE_AARCH64_URL="$aarch64_url" UPDATE_AARCH64_HASH="$aarch64_hash" \
python3 - <<'PY'
import os
import re
from pathlib import Path

path = Path(os.environ["FLAKE_FILE"])
text = path.read_text(encoding="utf-8")
version = os.environ["UPDATE_VERSION"]

begin = "# BEGIN swift-distributions (generated by Scripts/update-flake-swift.sh)"
end = "# END swift-distributions"
if begin not in text or end not in text:
    raise SystemExit("update-flake-swift: flake.nix is missing the swift-distributions markers")

block = "\n".join([
    begin,
    "        swiftDistributions = {",
    "          x86_64-linux = {",
    f'            url = "{os.environ["UPDATE_X86_URL"]}";',
    f'            hash = "{os.environ["UPDATE_X86_HASH"]}";',
    "          };",
    "          aarch64-linux = {",
    f'            url = "{os.environ["UPDATE_AARCH64_URL"]}";',
    f'            hash = "{os.environ["UPDATE_AARCH64_HASH"]}";',
    "          };",
    "        };",
    end,
])

pattern = re.compile(re.escape(begin) + r".*?" + re.escape(end), re.DOTALL)
text, count = pattern.subn(lambda _: block, text, count=1)
if count != 1:
    raise SystemExit("update-flake-swift: could not locate exactly one swift-distributions block")

text, version_count = re.subn(
    r'swiftVersion = "[0-9]+\.[0-9]+\.[0-9]+";',
    f'swiftVersion = "{version}";',
    text,
    count=1,
)
if version_count != 1:
    raise SystemExit("update-flake-swift: could not locate the swiftVersion binding")

path.write_text(text, encoding="utf-8")
PY

printf 'update-flake-swift: pinned Swift %s\n' "$version"
printf '  x86_64-linux  %s\n' "$x86_url"
printf '  aarch64-linux %s\n' "$aarch64_url"
